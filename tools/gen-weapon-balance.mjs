// Offline balance pass (v9.1): measures every weapon with src/data/balanceModel.js at three build points
// (no upgrade/no points, +10/half points, +20/max points) in both modes and writes src/data/weaponBalance.js —
// one farm multiplier and one PvP multiplier per weapon. Run:  node tools/gen-weapon-balance.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { allWeapons, weaponIndex } from '../src/data/balanceModel.js';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const W = allWeapons();
const W8 = { low: 0.2, mid: 0.3, max: 0.5 };
const gm = (id, mode) => Math.exp(Object.entries(W8).reduce((a, [sc, w]) => a + w * Math.log(weaponIndex(id, sc, mode)), 0));
const med = (a) => { const s = [...a].sort((x, y) => x - y), n = s.length; return n % 2 ? s[(n - 1) / 2] : (s[n / 2 - 1] + s[n / 2]) / 2; };

const MYTHIC_BASE = ['w_sunblade', 'w_sun_moon_twins'];
const SPECIAL = new Set(['w_eclipse_blade', 'w_heaven_scythe', 'w_sovereign_twins', 'w_sun_yoru', 'w_soul_eye_staff']);

const groups = {};
for (const w of W) {
  if (w.rarity === 'mythic' && !MYTHIC_BASE.includes(w.id)) continue;
  (groups[w.rarity] ||= []).push(w);
}
const target = {};
for (const [g, L] of Object.entries(groups)) target[g] = { farm: med(L.map((w) => gm(w.id, 'farm'))), pvp: med(L.map((w) => gm(w.id, 'pvp'))) };

const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));
const r2 = (v) => Math.round(v * 100) / 100;
// pull a weapon part of the way to its band; leave a ±4% dead zone so near-band weapons stay untouched
function pull(ratio, strength, lo, hi) {
  const dev = Math.log(ratio);
  const dz = 0.04;
  const eff = Math.abs(dev) <= dz ? 0 : dev - Math.sign(dev) * dz;
  return clamp(Math.exp(eff * strength), lo, hi);
}

const out = {};
for (const w of W) {
  const t = target[w.rarity];
  let farm, pvp;
  if (SPECIAL.has(w.id)) {
    // hand-set targets for the five weapons with a story of their own (multiplier on top of their current index)
    const SP = {
      w_eclipse_blade: { farm: 0.78, pvp: 0.80, why: 'ดาบลับสุดท้าย Boss Rush แรงเกินเทียร์ถึง 3 เท่า ลดลงแต่ยังเป็นอาวุธที่แรงที่สุดกลุ่มลับ' },
      w_heaven_scythe: { farm: 1.0, pvp: 0.94, why: 'ฟาร์มแรงขึ้นจากตัวเลขตราพิพากษาที่เพิ่ม · PvP ลดสัดส่วนตราพิพากษาและลดดาเมจรวม' },
      w_sovereign_twins: { farm: 1.07, pvp: 0.95, why: 'ฟาร์มแรงขึ้น (เงามังกรฟันซ้ำแรงขึ้น) · PvP ลดสเกลพลังเฉพาะลง' },
      w_sun_yoru: { farm: 1.0, pvp: 1.0, why: 'อยู่ในแถบที่ตั้งใจไว้ (อ่อนกว่าเคียวสวรรค์และดาบคู่ลับ) ไม่แตะ' },
      w_soul_eye_staff: { farm: 1.18, pvp: 0.96, why: 'ฟาร์มแรงขึ้น (พันเนตรลืมตาโดนเป้าได้มากขึ้น) · PvP ปรับเทียบให้ต่ำลงเล็กน้อยตามที่สั่ง' },
    };
    const s = SP[w.id];
    farm = s.farm; pvp = s.pvp; out[w.id] = { farm: r2(farm), pvp: r2(pvp), why: s.why, special: true };
    continue;
  }
  farm = pull(t.farm / gm(w.id, 'farm'), 0.8, 0.84, 1.22);
  pvp = pull(t.pvp / gm(w.id, 'pvp'), 0.7, 0.85, 1.18);
  out[w.id] = { farm: r2(farm), pvp: r2(pvp) };
}

const lines = Object.entries(out).map(([id, v]) => `  ${id}: { farm: ${v.farm.toFixed(2)}, pvp: ${v.pvp.toFixed(2)}${v.special ? `, special: true, why: ${JSON.stringify(v.why)}` : ''} },`);
const body = `// Weapon balance (v9.1) — GENERATED by tools/gen-weapon-balance.mjs from src/data/balanceModel.js. Do not edit by hand;
// change the model or the SPECIAL table in the tool and run it again.
//   farm — damage multiplier in the dungeon, story, raids, tower and online hunting zones
//   pvp  — damage multiplier in duels and team matches
// 1.00 = unchanged. >1.00 is a BUFF, <1.00 is a NERF. Applied in battle/uniques.js (uniqueDamageMult), which every
// damage path already calls, so one table covers every scene.
export const WEAPON_BAL = Object.freeze({
${lines.join('\n')}
});
export const balOf = (id) => WEAPON_BAL[id] || null;
`;
writeFileSync(join(ROOT, 'src/data/weaponBalance.js'), body);
const buffs = Object.entries(out).filter(([, v]) => v.farm >= 1.04 || v.pvp >= 1.04).length;
const nerfs = Object.entries(out).filter(([, v]) => v.farm <= 0.96 || v.pvp <= 0.96).length;
console.log('written', Object.keys(out).length, 'weapons; buff', buffs, 'nerf', nerfs);
console.log(JSON.stringify(target));
