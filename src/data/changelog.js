const KEY = 'emberhold.seenVersion';
export function seenVersion() { try { return localStorage.getItem(KEY) || ''; } catch { return ''; } }
export function markSeen(v = GAME_VERSION) { try { localStorage.setItem(KEY, v); } catch { /* storage blocked: the notes may show again, which is harmless */ } }
export const hasUnseenNotes = () => seenVersion() !== GAME_VERSION;
